test('an omitted wording reopens as a clickable box with its editable sidebar options', async t => {
  const { open, close } = await desktopFixture(t)
  let page = await open()
  const food = () => page.locator('.ProseMirror:visible [data-choice-id="kitchen-food"]')
  const nested = () => page.getByRole('region', { name: 'Within this passage' })
  const box = await food().boundingBox()
  await page.mouse.click(box.x + box.width - 1, box.y + box.height / 2)
  for (let i = 0; i < 4; i++) await page.keyboard.press('Backspace')
  assert.equal(await button(nested(), '(Empty wording)').getAttribute('aria-pressed'), 'true')
  assert.equal(await food().evaluate(el => el === getSelection().anchorNode), true, 'the visible caret is inside the empty box')
  await button(nested(), 'ice cream').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Edit wording' }).click()
  await page.keyboard.type('sorbet')
  await button(page, 'Save wording').click()
  await close()
  page = await open()
  await food().click()
  assert.equal(await food().evaluate(el => el === getSelection().anchorNode), true)
  assert.equal(await button(nested(), 'sorbet').getAttribute('aria-pressed'), 'false')
  await page.keyboard.type('cake')
  assert.equal(await food().textContent(), 'cake')
  await button(nested(), 'cake').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Delete wording' }).click()
  assert.equal(await food().count(), 0)
  assert.equal(await page.locator('.ProseMirror:visible [data-choice-id="kitchen-sentence"]').textContent(), 'I want to eat sorbet.')
})

test('history aligns changed lines in both windows and uses the manuscript line-number setting', async t => {
  const fixture = await desktopFixture(t)
  const page = await fixture.open()
  await page.evaluate(async () => {
    const { path, project } = await window.tinto.workspace()
    const doc = project.documents[0]
    const block = (id, text) => ({ type: 'paragraph', attrs: { id }, content: [{ type: 'text', text }] })
    const lines = Array.from({ length: 65 }, (_, i) => block('p' + i, 'Original passage ' + i))
    doc.manuscript.content = lines
    window.tinto.save(path, project.id, doc)
    await window.tinto.nameVersion(doc.id, 'First draft')
    lines[3].content[0].text = 'The quick brown fox'
    window.tinto.save(path, project.id, doc)
    await window.tinto.nameVersion(doc.id, 'Second draft')
    lines[3].content[0].text = 'The slow brown fox'
    lines.splice(1, 0, block('insert', 'An added line'))
    lines.splice(8, 1)
    for (const line of lines.slice(10)) line.content[0].text += ' revised'
    window.tinto.save(path, project.id, doc)
  })
  await page.reload()
  await button(page, 'History').click()
  const modal = page.getByRole('dialog')
  const picker = modal.getByRole('combobox', { name: 'Saved version' })
  await picker.waitFor()
  assert.match(await picker.locator('option:checked').innerText(), /Second draft/)
  assert.equal(await modal.getByText('Original passage 0', { exact: true }).count(), 0)
  assert.equal(await modal.locator('.history-line-number:visible').count(), 0)
  const rows = modal.locator('tbody tr')
  assert.deepEqual(await rows.nth(0).locator('td').allTextContents(), ['2An added line', ''])
  assert.deepEqual(await rows.nth(1).locator('ins, del').allTextContents(), ['slow', 'quick'])
  assert.deepEqual(await rows.nth(1).locator('.history-line-number').allTextContents(), ['5', '4'])
  assert.deepEqual(await rows.nth(2).locator('td').allTextContents(), ['', '8Original passage 7'])
  await button(modal, 'Close history').click()
  await button(page, 'Reading and project settings').click()
  await page.getByRole('tab', { name: 'Writing' }).click()
  const numbers = page.getByRole('checkbox', { name: 'Show line numbers' })
  assert.equal(await numbers.isChecked(), false)
  await numbers.check()
  await button(page, 'Close dialog').click()
  await page.reload()
  const paragraph = page.locator('.ProseMirror:visible > p').nth(4)
  await paragraph.waitFor()
  assert.equal(await paragraph.evaluate(node => getComputedStyle(node, '::before').counterSet), 'manuscript-line 5')
  await button(page, 'History').click()
  await picker.waitFor()
  const opened = fixture.app.waitForEvent('window')
  await button(modal, 'Open in separate window').click()
  const expanded = await opened
  const expandedRows = expanded.locator('tbody tr')
  await expandedRows.first().waitFor()
  assert.deepEqual(await expandedRows.nth(1).locator('.history-line-number:visible').allTextContents(), ['5', '4'])
  assert.equal(await expandedRows.count(), await rows.count())
  await expandedRows.last().scrollIntoViewIfNeeded()
  assert.match(await expandedRows.last().innerText(), /Original passage 64 revised/)
  await expanded.getByRole('combobox', { name: 'Saved version' }).selectOption({ index: 1 })
  assert.match(await picker.locator('option:checked').innerText(), /First draft/)
  assert.equal(await expandedRows.nth(1).locator('.past .history-prose').innerText(), 'Original passage 3')
  const closed = expanded.waitForEvent('close')
  await (await fixture.app.browserWindow(expanded)).evaluate(win => win.close())
  await closed
  await button(modal, 'Close history').click()
})

