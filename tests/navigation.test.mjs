test('dragging a document onto another project moves it and its history through Home', async t => {
  const fixture = await desktopFixture(t)
  let page = await fixture.open()
  const button = name => page.getByRole('button', { name, exact: true })
  const source = await page.evaluate(() => window.tinto.workspace())
  const doc = source.project.documents[0]
  await page.evaluate(id => window.tinto.nameVersion(id, 'Before moving'), doc.id)
  const destination = join(fixture.folder, 'Second project.tinto')
  await fixture.app.evaluate(({ dialog }, filePath) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath })
  }, destination)
  await button('Home').click()
  await button('New project').click()
  await page.getByText('No documents yet.', { exact: true }).waitFor()
  await page.getByTitle(source.path, { exact: true }).click()
  const row = page.locator('#home .doc-row').filter({ hasText: doc.title })
  await row.dragTo(page.getByTitle(source.path, { exact: true }))
  assert.equal(await row.count(), 1)
  await row.dragTo(page.getByTitle(destination, { exact: true }))
  await page.getByText('No documents yet.', { exact: true }).waitFor()
  assert.deepEqual(await page.locator('#tabs .tab-label').allTextContents(), ['Home'])
  assert.deepEqual((await page.evaluate(() => window.tinto.workspace())).project.documents, [])
  const undoMove = () => page.locator('#notice').getByRole('button', { name: 'Undo', exact: true }).click()
  await undoMove()
  await row.waitFor()
  assert.deepEqual((await page.evaluate(() => window.tinto.workspace())).project.documents, [doc])
  assert.equal((await page.evaluate(id => window.tinto.versions(id), doc.id))[0].name, 'Before moving')
  await row.dragTo(page.getByTitle(destination, { exact: true }))
  await row.waitFor({ state: 'detached' })
  await page.getByTitle(destination, { exact: true }).click()
  await row.click()
  await page.locator('.ProseMirror:visible').waitFor()
  await fixture.close()
  page = await fixture.launch()
  await page.locator('.ProseMirror:visible').waitFor()
  const reopened = await page.evaluate(() => window.tinto.workspace())
  assert.equal(reopened.path, destination)
  assert.deepEqual(reopened.project.documents, [doc])
  assert.equal((await page.evaluate(id => window.tinto.versions(id), doc.id))[0].name, 'Before moving')

  await button('Create draft').click()
  await page.getByLabel('Draft name').fill('Other ending')
  await page.getByRole('dialog').getByRole('button', { name: 'Create draft' }).click()
  await button('Review draft').waitFor()
  await button('Home').click()
  const draft = page.locator('#home .doc-row').filter({ hasText: 'Other ending' })
  const originalProject = page.getByTitle(source.path, { exact: true })
  await draft.dragTo(originalProject)
  await button('Cancel').click()
  assert.equal((await page.evaluate(() => window.tinto.workspace())).project.documents[1].source.documentId, doc.id)
  await draft.dragTo(originalProject)
  await button('Move').click()
  await draft.waitFor({ state: 'detached' })
  await originalProject.click()
  await draft.click()
  await button('Create draft').waitFor()
  await undoMove()
  await page.getByText('No documents yet.', { exact: true }).waitFor()
  await page.getByTitle(destination, { exact: true }).click()
  await draft.click()
  await button('Review draft').waitFor()
})

