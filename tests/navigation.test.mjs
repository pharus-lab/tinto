test('Home renames project files and trashes the chosen project without switching to it', async t => {
  const fixture = await desktopFixture(t)
  const page = await fixture.open()
  const button = name => page.getByRole('button', { name, exact: true })
  const action = name => page.getByRole('menuitem', { name, exact: true })
  const workspace = () => page.evaluate(() => window.tinto.workspace())
  const original = await workspace()
  const otherPath = join(fixture.folder, 'Another.tinto')
  await copyFile(original.path, otherPath)
  await page.evaluate(() => window.tinto.enableBackup(true))
  await button('Home').click()
  await page.getByTitle(original.path, { exact: true }).click({ button: 'right' })
  await action('Rename').click()
  const name = page.getByLabel('Project name')
  await name.fill('Another')
  await button('Rename').click()
  await page.getByRole('alert').filter({ hasText: 'already exists' }).waitFor()
  await name.fill('Revised')
  await button('Rename').click()
  const revised = join(fixture.folder, 'Revised.tinto')
  await page.getByTitle(revised, { exact: true }).waitFor()
  assert.deepEqual((await readdir(fixture.folder)).sort(), ['Another.tinto', 'Revised.tinto'])
  assert.equal((await workspace()).project.id, original.project.id)
  assert.equal((await workspace()).project.title, 'Revised')
  assert.equal(await page.evaluate(async () => (await window.tinto.backupStatus()).enabled), true)
  await page.reload()
  await page.getByTitle(otherPath, { exact: true }).click({ button: 'right' })
  await action('Rename').click()
  await name.fill('Spare')
  await button('Rename').click()
  const spare = join(fixture.folder, 'Spare.tinto')
  await page.getByTitle(spare, { exact: true }).click({ button: 'right' })
  await action('Delete').click()
  await button('Cancel').click()
  // Keep test projects inside the disposable fixture instead of the writer's Trash.
  await fixture.app.evaluate(({ shell }, directory) => {
    shell.trashItem = path => process.getBuiltinModule('fs/promises').rename(path, directory + '/' + process.getBuiltinModule('path').basename(path))
  }, fixture.directory)
  for (const path of [spare, revised]) {
    const row = page.getByTitle(path, { exact: true })
    assert.equal((await workspace()).path, revised)
    await row.click({ button: 'right' })
    await action('Delete').click()
    await button('Delete').click()
    await row.waitFor({ state: 'detached' })
    assert.ok((await stat(join(fixture.directory, path.split('/').pop()))).isFile())
  }
  await button('Open sample project').waitFor()
  assert.equal((await page.evaluate(() => window.tinto.library())).workspace, null)
})

test('a centered column is the default and narrows to fit without scrolling sideways, while margins keep their size', async t => {
  const fixture = await desktopFixture(t)
  const page = await fixture.open()
  const settings = page.getByRole('button', { name: 'Reading and project settings' })
  const mode = page.getByLabel('Text width')
  const margin = page.getByLabel('Margin on each side (px)')
  const column = page.getByLabel('Column width (px)')
  async function resize(width) {
    await fixture.app.evaluate(({ BrowserWindow }, width) => BrowserWindow.getAllWindows()[0].setContentSize(width, 720), width)
    await page.waitForFunction(width => window.innerWidth === width, width)
  }
  function geometry() {
    return page.locator('.ProseMirror:visible').evaluate(editor => {
      const pane = document.getElementById('scroll')
      const left = editor.getBoundingClientRect().left - pane.getBoundingClientRect().left
      const width = editor.getBoundingClientRect().width
      return { left, width, right: pane.clientWidth - width - left }
    })
  }
  const writing = () => page.getByRole('tab', { name: 'Writing' }).click()
  const sideways = () => page.locator('#scroll').evaluate(pane => pane.scrollWidth > pane.clientWidth)
  await resize(1100)
  await settings.click()
  await writing()
  const controls = page.getByRole('dialog').getByRole('combobox')
  const widths = await controls.evaluateAll(controls => controls.map(control => control.offsetWidth))
  assert.equal(new Set(widths).size, 1)
  const clipped = await controls.evaluateAll(controls => {
    const context = document.createElement('canvas').getContext('2d')
    return controls.flatMap(control => {
      const style = getComputedStyle(control)
      context.font = style.font
      const space = control.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight)
      return Array.from(control.options).map(option => option.text).filter(text => context.measureText(text).width > space)
    })
  })
  assert.deepEqual(clipped, [])
  assert.deepEqual(await mode.locator('option').allTextContents(), ['Fixed Width', 'Fixed Margin'])

  // A new writer starts with a centered column of about 66 characters.
  assert.equal(await mode.inputValue(), 'fixed-width')
  assert.equal(await column.inputValue(), '680')
  await column.fill('640')
  const fixed = await geometry()
  assert.equal(fixed.width, 640)
  assert.ok(Math.abs(fixed.left - fixed.right) <= 1)
  // Where the column does not fit, it narrows and keeps 24px each side, never scrolling sideways.
  await resize(800)
  const narrowed = await geometry()
  assert.ok(narrowed.width < 640)
  assert.deepEqual([Math.round(narrowed.left), Math.round(narrowed.right)], [24, 24])
  assert.equal(await sideways(), false)
  await resize(1100)
  assert.equal((await geometry()).width, 640)

  await mode.selectOption({ label: 'Fixed Margin' })
  assert.equal(await margin.inputValue(), '48')
  await margin.fill('62')
  const wide = await geometry()
  assert.deepEqual([wide.left, wide.right], [62, 62])
  await resize(800)
  const narrow = await geometry()
  assert.deepEqual([narrow.left, narrow.right], [62, 62])
  assert.ok(narrow.width < wide.width)

  await page.reload()
  await settings.click()
  await writing()
  assert.equal(await mode.inputValue(), 'fixed-margin')
  assert.equal(await margin.inputValue(), '62')
  await page.evaluate(() => {
    const saved = JSON.parse(localStorage.getItem('reading'))
    saved.textWidth = 'free'
    localStorage.setItem('reading', JSON.stringify(saved))
  })
  await page.reload()
  await settings.click()
  await writing()
  assert.equal(await mode.inputValue(), 'fixed-width')
  assert.equal(await column.inputValue(), '640')
})

test('headings jump in place and explicit spawns form a collapsed tree across restarts', async t => {
  const fixture = await desktopFixture(t)
  let page = await fixture.open()
  const button = name => page.getByRole('button', { name, exact: true })
  const outline = () => page.getByRole('navigation', { name: 'Manuscript headings' })
  const source = () => page.locator('#tabs').getByRole('button', { name: 'The long way home', exact: true })
  const visibleSpawns = () => page.locator('#home .section-row:visible').allTextContents()
  await page.evaluate(async () => {
    const { project, path } = await window.tinto.workspace()
    const doc = project.documents[0]
    const heading = (id, title, level) => ({ type: 'heading', attrs: { id, level }, content: [{ type: 'text', text: title }] })
    const blocks = doc.manuscript.content
    blocks.splice(3, 0, heading('shelves', 'The shelves', 2), heading('cup', 'The cup', 3))
    blocks.splice(-2, 0, heading('pear', 'The pear tree', 2))
    const error = window.tinto.save(path, project.id, doc)
    if (error) throw Error(error)
  })
  await page.reload()
  await button('Home').click()
  await page.locator('#home .doc-row').waitFor()
  assert.equal(await button('Expand The long way home').count(), 0)
  assert.deepEqual(await visibleSpawns(), [])
  await source().click()
  await button('Headings').click()
  assert.deepEqual(await outline().locator('.heading-jump').allTextContents(), ['The kitchen', 'The shelves', 'The cup', 'The garden', 'The pear tree'])
  await outline().getByRole('button', { name: 'The pear tree', exact: true }).click()
  assert.equal(await source().getAttribute('aria-current'), 'page')
  assert.equal(await page.evaluate(() => getSelection().anchorNode.parentElement.closest('[data-block-id]').dataset.blockId), 'pear')
  assert.ok(await page.locator('#scroll').evaluate(el => el.scrollTop > 0))
  assert.equal(await page.locator('#tabs .tab').count(), 2)

  const pear = page.locator('.ProseMirror [data-block-id=pear]')
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+ArrowRight' : 'End')
  await page.keyboard.insertText('s')
  assert.equal(await pear.textContent(), 'The pear trees')
  await page.keyboard.press('Backspace')
  assert.equal(await pear.textContent(), 'The pear tree')
  await pear.hover()
  for (const width of ['', '150px']) {
    const geometry = await pear.evaluate((heading, width) => {
      heading.closest('#editors').style.maxWidth = width
      const text = document.createTreeWalker(heading, NodeFilter.SHOW_TEXT)
      let last = text.nextNode()
      while (text.nextNode()) last = text.currentNode
      const character = document.createRange()
      character.setStart(last, last.length - 1)
      character.setEnd(last, last.length)
      const end = character.getBoundingClientRect()
      const action = heading.querySelector('.spawn-button').getBoundingClientRect()
      return { gap: action.left - end.right, center: action.top + action.height / 2, top: end.top, bottom: end.bottom, lines: heading.offsetHeight / parseFloat(getComputedStyle(heading).lineHeight) }
    }, width)
    assert.ok(geometry.gap >= 0 && geometry.gap <= 8, JSON.stringify(geometry))
    assert.ok(geometry.center >= geometry.top && geometry.center <= geometry.bottom, JSON.stringify(geometry))
    assert.equal(Math.round(geometry.lines) > 1, !!width)
  }
  await page.locator('#editors').evaluate(el => { el.style.maxWidth = '' })
  await pear.hover()
  await pear.getByRole('button', { name: 'Create spawn for The pear tree' }).click()
  assert.equal(await page.locator('.ProseMirror [data-block-id]:visible').first().getAttribute('data-block-id'), 'pear')
  await source().click()
  await button('Headings').click()
  await outline().getByRole('button', { name: 'Create spawn for The kitchen' }).click()
  await button('Headings').click()
  assert.deepEqual(await outline().locator('.heading-jump').allTextContents(), ['The kitchen', 'The shelves', 'The cup'])
  await outline().getByRole('button', { name: 'Create spawn for The cup' }).click()
  await source().click()
  await button('Headings').click()
  await outline().getByRole('button', { name: 'Open spawn for The cup' }).click()
  assert.equal(await page.locator('#tabs .current .tab-label').textContent(), 'The cup')
  assert.equal(await page.locator('#tabs .tab-label').filter({ hasText: 'The cup' }).count(), 1)

  await button('Home').click()
  await button('Expand The long way home').waitFor()
  await fixture.close()
  page = await fixture.launch()
  await button('Expand The long way home').waitFor()
  assert.deepEqual(await visibleSpawns(), [])
  await button('Expand The long way home').click()
  assert.deepEqual(await visibleSpawns(), ['The kitchen', 'The pear tree'])
  await button('Expand The kitchen').click()
  assert.deepEqual(await visibleSpawns(), ['The kitchen', 'The cup', 'The pear tree'])
  const depth = name => page.locator('#home .section-row').filter({ hasText: name }).evaluate(el => el.getBoundingClientRect().left)
  assert.equal(await depth('The kitchen'), await depth('The pear tree'))
  assert.ok(await depth('The cup') > await depth('The kitchen'))
  await button('Collapse The kitchen').click()
  assert.deepEqual(await visibleSpawns(), ['The kitchen', 'The pear tree'])
  await page.locator('#home').getByRole('button', { name: 'The pear tree', exact: true }).click()
  assert.equal(await page.locator('#tabs .current .tab-label').textContent(), 'The pear tree')
})

